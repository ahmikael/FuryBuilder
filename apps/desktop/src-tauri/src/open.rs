//! Opens fixed FuryBuilder-owned directories with the platform file manager.

use std::path::Path;
use std::process::Command;

/// Opens an existing directory. Callers pass a path derived from backend state, never a
/// path supplied directly by the frontend.
pub fn open_directory(path: &Path) -> Result<(), String> {
    #[cfg(target_os = "windows")]
    let mut command = {
        let mut command = Command::new("explorer.exe");
        command.arg(path);
        command
    };
    #[cfg(target_os = "macos")]
    let mut command = {
        let mut command = Command::new("open");
        command.arg(path);
        command
    };
    #[cfg(all(unix, not(target_os = "macos")))]
    let mut command = {
        let mut command = Command::new("xdg-open");
        command.arg(path);
        command
    };
    command
        .spawn()
        .map(|_| ())
        .map_err(|error| format!("opening {} failed: {error}", path.display()))
}
